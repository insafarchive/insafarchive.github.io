export function getCoverageEntryById(articleId: string): ConstitutionalArticleCoverageEntry | undefined {
  return CONSTITUTION_COVERAGE_REGISTER.find(e => e.articleId === articleId);
}

export function getCoverageEntryByNumber(num: string): ConstitutionalArticleCoverageEntry | undefined {
  const norm = num.trim().toLowerCase();
  return CONSTITUTION_COVERAGE_REGISTER.find(
    e => e.articleNumber.toLowerCase() === norm || e.articleId.toLowerCase() === `pk-const-a${norm}`
  );
}

export function getCoverageStatistics() {
  const total = CONSTITUTION_COVERAGE_REGISTER.length;
  const inCorpus = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.isInArticleCorpus).length;
  const englishVerified = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.englishStatus === 'source_verified').length;
  const urduVerified = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.urduStatus === 'official_verified').length;
  const clauseComplete = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.clauseCompleteness === 'complete').length;
  const structureOnly = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.verificationStatus === 'structure_only').length;
  const sourceRequired = CONSTITUTION_COVERAGE_REGISTER.filter(e => e.sourceCitationStatus === 'source_required').length;

  return {
    total,
    inCorpus,
    englishVerified,
    urduVerified,
    clauseComplete,
    structureOnly,
    sourceRequired,
  };
}
